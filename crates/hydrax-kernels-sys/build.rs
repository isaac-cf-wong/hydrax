//! Compile the Hydrax kernels and record what their header declared.
//!
//! Two jobs, and the second is the interesting one. Compiling the C is
//! routine. Reading the version and the conserved-variable count back out of
//! the header gives the crate a third, independent view of the ABI contract:
//! the constants written by hand in Rust, the macros written by hand in C, and
//! the values the compiled library reports at run time. A smoke test asserts
//! all three agree, which no two of them could establish on their own.

use std::{env, fmt::Write as _, fs, path::PathBuf};

/// Directory holding the kernel sources, relative to this crate.
const KERNELS_DIRECTORY: &str = "../../kernels";

/// Kernel translation units, relative to `kernels/src`.
const SOURCES: [&str; 2] = ["hydrax_kernels.c", "hydrax_kernels_hydro.c"];

/// One header macro the crate mirrors: the macro, the Rust constant it
/// becomes, that constant's type, and its documentation.
struct Mirrored {
    /// Name of the object-like macro in the header.
    macro_name: &'static str,
    /// Name of the generated Rust constant.
    constant: &'static str,
    /// Type of the generated Rust constant.
    kind: &'static str,
    /// Documentation for the generated Rust constant.
    documentation: &'static str,
}

/// Header macros the crate mirrors.
const MIRRORED_MACROS: [Mirrored; 4] = [
    Mirrored {
        macro_name: "HYDRAX_KERNELS_ABI_VERSION_MAJOR",
        constant: "ABI_VERSION_MAJOR",
        kind: "u8",
        documentation: "Major component of the ABI version the header declared.",
    },
    Mirrored {
        macro_name: "HYDRAX_KERNELS_ABI_VERSION_MINOR",
        constant: "ABI_VERSION_MINOR",
        kind: "u8",
        documentation: "Minor component of the ABI version the header declared.",
    },
    Mirrored {
        macro_name: "HYDRAX_KERNELS_ABI_VERSION_PATCH",
        constant: "ABI_VERSION_PATCH",
        kind: "u8",
        documentation: "Patch component of the ABI version the header declared.",
    },
    Mirrored {
        macro_name: "HYDRAX_KERNELS_CONSERVED_COUNT",
        constant: "CONSERVED_COUNT",
        kind: "usize",
        documentation: "Conserved variables per zone, as the header declared them.",
    },
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR").expect("cargo always sets CARGO_MANIFEST_DIR"),
    );
    let kernels = manifest.join(KERNELS_DIRECTORY);
    let include = kernels.join("include");
    let header = include.join("hydrax_kernels.h");

    // Cargo walks a watched directory, so this covers the header, every
    // translation unit, and any source added later without this list.
    println!("cargo:rerun-if-changed={}", kernels.display());

    let declarations = fs::read_to_string(&header)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", header.display()));
    write_header_constants(&declarations);

    let mut build = cc::Build::new();
    build.include(&include).std("c11").warnings(true);
    for source in SOURCES {
        build.file(kernels.join("src").join(source));
    }
    // The safe-Rust reference the C is differentially tested against performs
    // the same operations in the same order. Contraction into fused multiply
    // -add would change the rounding of the HLL average and the flux
    // divergence, and the tests would then be measuring the compiler's licence
    // to reassociate rather than the kernels.
    build.flag_if_supported("-ffp-contract=off");
    build.flag_if_supported("/fp:precise");
    build.compile("hydrax_kernels");
}

/// Emit the header's object-like macros as Rust constants.
fn write_header_constants(declarations: &str) {
    let mut generated = String::from(
        "// Generated by build.rs from kernels/include/hydrax_kernels.h.\n\
         // Edit the header, not this file.\n",
    );
    for mirrored in MIRRORED_MACROS {
        let Mirrored {
            macro_name,
            constant,
            kind,
            documentation,
        } = mirrored;
        let value = object_like_macro(declarations, macro_name).unwrap_or_else(|| {
            panic!("kernels/include/hydrax_kernels.h does not define {macro_name}")
        });
        writeln!(
            generated,
            "\n/// {documentation}\npub const {constant}: {kind} = {value};"
        )
        .expect("writing to a String cannot fail");
    }

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo always sets OUT_DIR"));
    let destination = out_dir.join("header_constants.rs");
    fs::write(&destination, generated)
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", destination.display()));
}

/// Read the integer value of an object-like `#define` from a C header.
///
/// The macro name is matched as a whole token rather than as a prefix, because
/// the version macros are prefixes of one another: `HYDRAX_KERNELS_ABI_VERSION`
/// would otherwise match the line defining its own major component.
fn object_like_macro(declarations: &str, name: &str) -> Option<u32> {
    declarations.lines().find_map(|line| {
        let mut tokens = line.trim_start().strip_prefix('#')?.split_whitespace();
        (tokens.next()? == "define" && tokens.next()? == name)
            .then(|| tokens.next())
            .flatten()?
            .parse()
            .ok()
    })
}
